-- Cross River Trading Co. -- constraint conformance
-- author: (fixture maintenance, not part of the Cross River story)
-- postgres: 18
--
-- Every kind of constraint PostgreSQL 18 supports, in one place, correctly
-- used. The defective uses live in the narrative schemas; these are the
-- controls to compare them against.

-- ---------------------------------------------------------------------------
-- Identity columns, both forms
-- ---------------------------------------------------------------------------

CREATE TABLE conformance.identity_always (
    id     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    label  text NOT NULL
);

CREATE TABLE conformance.identity_by_default (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label  text NOT NULL
);

-- ---------------------------------------------------------------------------
-- UNIQUE in its several forms
-- ---------------------------------------------------------------------------

CREATE TABLE conformance.unique_variants (
    id            integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    -- The default: two null values are distinct, so duplicates of null are
    -- permitted.
    nulls_distinct     text UNIQUE,
    -- The opposite: nulls compare equal, so only one null row is permitted.
    nulls_not_distinct text UNIQUE NULLS NOT DISTINCT,
    -- A unique key carrying a payload column in the index leaf.
    covering_key       integer,
    covering_payload   text,
    -- Checked at commit rather than at statement time.
    deferred_key       integer,
    CONSTRAINT unique_variants_covering UNIQUE (covering_key) INCLUDE (covering_payload),
    CONSTRAINT unique_variants_deferred UNIQUE (deferred_key) DEFERRABLE INITIALLY DEFERRED
);

-- ---------------------------------------------------------------------------
-- Foreign keys: every referential action, and both MATCH modes
-- ---------------------------------------------------------------------------

CREATE TABLE conformance.fk_parent (
    parent_id   integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    part_a      integer NOT NULL,
    part_b      integer NOT NULL,
    CONSTRAINT fk_parent_composite UNIQUE (part_a, part_b)
);

CREATE TABLE conformance.fk_actions (
    id           integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    on_cascade   integer REFERENCES conformance.fk_parent (parent_id) ON DELETE CASCADE,
    on_restrict  integer REFERENCES conformance.fk_parent (parent_id) ON DELETE RESTRICT,
    on_set_null  integer REFERENCES conformance.fk_parent (parent_id) ON DELETE SET NULL,
    on_no_action integer REFERENCES conformance.fk_parent (parent_id) ON DELETE NO ACTION,
    on_set_default integer DEFAULT 1 REFERENCES conformance.fk_parent (parent_id) ON DELETE SET DEFAULT,
    on_update_cascade integer REFERENCES conformance.fk_parent (parent_id) ON UPDATE CASCADE,
    deferred_ref integer REFERENCES conformance.fk_parent (parent_id) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE conformance.fk_match_full (
    id      integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    part_a  integer,
    part_b  integer,
    -- MATCH FULL: either both columns are null, or both must match a parent.
    -- This is what marketing.applied_promotions should have used.
    CONSTRAINT fk_match_full_both
        FOREIGN KEY (part_a, part_b)
        REFERENCES conformance.fk_parent (part_a, part_b) MATCH FULL
);

-- Self-referencing hierarchy.
CREATE TABLE conformance.fk_self (
    node_id    integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    parent_id  integer REFERENCES conformance.fk_self (node_id),
    label      text NOT NULL
);

-- ---------------------------------------------------------------------------
-- CHECK constraints: table level, column level, NO INHERIT
-- ---------------------------------------------------------------------------

CREATE TABLE conformance.check_variants (
    id         integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    low        integer CHECK (low >= 0),
    high       integer,
    -- Not inherited by child tables.
    local_only integer CHECK (local_only < 1000) NO INHERIT,
    CONSTRAINT check_variants_ordered CHECK (high IS NULL OR low IS NULL OR high >= low)
);

-- ---------------------------------------------------------------------------
-- Exclusion constraint, done properly
-- ---------------------------------------------------------------------------

CREATE TABLE conformance.room_bookings (
    booking_id  integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    room_id     integer NOT NULL,
    during      tstzrange NOT NULL,
    -- No two bookings for the same room may overlap in time.
    EXCLUDE USING gist (room_id WITH =, during WITH &&)
);

-- ---------------------------------------------------------------------------
-- Temporal constraints, the PostgreSQL 18 form
-- ---------------------------------------------------------------------------

CREATE TABLE conformance.rate_periods (
    rate_id      integer NOT NULL,
    valid_during daterange NOT NULL,
    rate_pct     numeric(5,2) NOT NULL,
    PRIMARY KEY (rate_id, valid_during WITHOUT OVERLAPS)
);

CREATE TABLE conformance.rate_usage (
    rate_id     integer NOT NULL,
    used_during daterange NOT NULL,
    FOREIGN KEY (rate_id, PERIOD used_during)
        REFERENCES conformance.rate_periods (rate_id, PERIOD valid_during)
);

-- ---------------------------------------------------------------------------
-- Domain constraints
-- ---------------------------------------------------------------------------

CREATE TABLE conformance.domain_usage (
    id        integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    postcode  conformance.postcode,
    quantity  conformance.positive_int
);

-- ---------------------------------------------------------------------------
-- Constraint trigger, deferred to commit
-- ---------------------------------------------------------------------------

CREATE TABLE conformance.trigger_checked (
    id     integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    total  integer NOT NULL DEFAULT 0
);

CREATE FUNCTION conformance.fn_total_non_negative() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.total < 0 THEN
        RAISE EXCEPTION 'total must not be negative (got %)', NEW.total;
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_total_non_negative
    AFTER INSERT OR UPDATE ON conformance.trigger_checked
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION conformance.fn_total_non_negative();

-- ---------------------------------------------------------------------------
-- Row level security
-- ---------------------------------------------------------------------------

CREATE TABLE conformance.rls_protected (
    id       integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    owner    name NOT NULL DEFAULT current_user,
    secret   text
);

ALTER TABLE conformance.rls_protected ENABLE ROW LEVEL SECURITY;

CREATE POLICY rls_protected_owner ON conformance.rls_protected
    FOR ALL USING (owner = current_user);

CREATE POLICY rls_protected_no_delete ON conformance.rls_protected
    AS RESTRICTIVE FOR DELETE USING (false);

-- ---------------------------------------------------------------------------
-- Collation, which changes what UNIQUE means
-- ---------------------------------------------------------------------------

CREATE COLLATION conformance.case_insensitive (
    provider = icu,
    locale = 'und-u-ks-level2',
    deterministic = false
);

CREATE TABLE conformance.collated_keys (
    id            integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    -- Unique under the default collation: 'Alice' and 'alice' are two rows.
    default_key   text UNIQUE,
    -- Unique under a case-insensitive collation: they are one row.
    ci_key        text COLLATE conformance.case_insensitive UNIQUE
);

