-- Cross River Trading Co. -- autumn campaign codes, review queues, product revenue
-- author: R. Okonjo
-- postgres: 18
--
-- The autumn 2026 campaign needed its own code table, because marketing had
-- outgrown the one-code-per-coupon model. The rest of this migration is the
-- reporting the same team asked for in the same fortnight: a review queue, a
-- repeat-customer number for the board pack, a household view for the legacy
-- data, and a product revenue rollup for the dashboard.

-- DEFECT identity-by-default-leaves-the-sequence-behind
--
-- The codes were generated in a spreadsheet, numbered there, and loaded with
-- their numbers intact so the print run and the database would agree. That is
-- why the column is GENERATED BY DEFAULT AS IDENTITY rather than ALWAYS: BY
-- DEFAULT permits an explicit value, and the load needed one.
--
-- An explicit value does not advance the sequence. Nothing in PostgreSQL
-- reconciles the two afterwards, and no error is raised at load time, so the
-- table now holds 600 rows numbered 1 to 600 behind a sequence that has never
-- been called and will hand out 1 the first time it is.
--
-- Measured: max(code_id) is 600 and the sequence's last_value is 1, a gap of
-- 599. The next insert that lets the identity column default will collide with
-- the row that already holds 1, and so will the 599 attempts after it.
--
-- The table is only written by the annual load today, and the annual load
-- always supplies its own numbers, so the defect is invisible until the first
-- person adds a single code by hand. It is the same shape as a restored dump
-- with no setval, which is how most people meet it.
CREATE TABLE marketing.campaign_codes (
    code_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        varchar(40) NOT NULL UNIQUE,
    wave        varchar(20) NOT NULL,
    percent_off integer NOT NULL CHECK (percent_off BETWEEN 1 AND 100),
    created_at  timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE marketing.campaign_codes IS
    'Autumn 2026 campaign codes. Loaded with explicit ids to match the print run.';

