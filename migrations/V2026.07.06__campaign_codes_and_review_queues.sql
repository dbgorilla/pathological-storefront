-- DEFECT underscore-wildcard-matches-any-character
--
-- Marketing needed a count per wave, and a wave is identified by the front of
-- the code. The routine takes that prefix and puts it in a LIKE pattern.
--
-- LIKE has two wildcards and the second one is easy to forget. Underscore
-- matches exactly one character of anything. 'AUTUMN_2026' is not a literal
-- string to LIKE, it is a pattern that matches AUTUMN_2026 and AUTUMN-2026 and
-- AUTUMNX2026 alike. Equality would have been safe and so would an escaped
-- pattern; the unescaped LIKE is the one that looks fine.
--
-- Measured: fn_codes_in_wave('AUTUMN_2026') returns 600. There are 300 codes
-- in that wave. The other 300 are the legacy loader's hyphenated codes, which
-- are a different wave for a real business reason: they carry a different
-- supplier and a different reconciliation.
--
-- The count has never looked wrong, because 600 is a plausible number for a
-- campaign this size and nobody has a second source to check it against. The
-- discount forecast built on it is out by a factor of two.
CREATE FUNCTION marketing.fn_codes_in_wave(p_prefix text)
RETURNS bigint
LANGUAGE sql
STABLE
AS $$
    SELECT count(*)
      FROM marketing.campaign_codes
     WHERE code LIKE p_prefix || '%';
$$;

COMMENT ON FUNCTION marketing.fn_codes_in_wave(text) IS
    'Count of codes in a wave, by code prefix.';

-- DEFECT having-without-group-by-collapses-to-one-row
--
-- The board pack wants the number of customers who order repeatedly, which the
-- author defined as more than ten orders. The HAVING clause says exactly that
-- and the view reads as though it does it.
--
-- HAVING without GROUP BY does not filter customers. It filters the single
-- aggregate row the query already produces, so the condition asked is whether
-- the whole table has more than ten orders. It has 13,880, the condition is
-- true, the row survives, and the count in it is every customer who has ever
-- ordered. The filter cannot remove anything except the row itself, and it
-- never will.
--
-- Measured: the view returns 2,730. The number of customers with more than ten
-- orders is 30. It is wrong by ninety-one times.
--
-- Nothing errors and nothing looks empty, which is the whole problem: a view
-- that returns one plausible number is the hardest kind to doubt. The figure
-- has been in the board pack for two quarters as "repeat customers", and it is
-- in fact "customers".
CREATE VIEW analytics.v_repeat_customer_count AS
SELECT count(DISTINCT o.customer_id) AS repeat_customers
FROM storefront.orders o
HAVING count(*) > 10;

-- DEFECT and-or-precedence-without-parentheses
--
-- The review queue is meant to hold pending orders that are either large or
-- carry a gift message, because those are the two things a human has to look
-- at before the order ships. Read the WHERE clause aloud and that is what it
-- appears to say.
--
-- AND binds tighter than OR. Without parentheses the clause means (pending AND
-- large) OR (has a gift message), and the second branch has no status test at
-- all. Every order with a gift message is in the queue regardless of status,
-- including the ones already shipped and the ones cancelled.
--
-- Measured: the view returns 1,695 orders. The intended filter returns 922.
-- The 773 extra rows are orders nobody can act on, and the queue is worked
-- top-down, so the ones that can be acted on are not reliably reached.
--
-- The screen has a "nothing to do here" problem rather than a wrong-answer
-- problem, which is why it has been tolerated for a year. Two brackets fix it.
CREATE VIEW storefront.v_orders_for_review AS
SELECT o.order_id,
       o.customer_id,
       o.status,
       o.total_cents,
       o.gift_message,
       o.placed_at
FROM storefront.orders o
WHERE o.status = 'pending' AND o.total_cents >= 50000 OR o.gift_message IS NOT NULL;

-- DEFECT self-join-without-excluding-the-row-itself
--
-- Fraud review wanted addresses that more than one customer uses, which is a
-- self-join on postcode. The join is written correctly except for the one
-- predicate that a self-join always needs and that nothing warns you about.
--
-- Without b.id <> a.id every row joins to itself. An address whose postcode is
-- unique in the table still produces a pair, and reads exactly like an address
-- shared with somebody.
--
-- Measured: the view returns 1,260 pairs. Only 60 are real. The other 1,200
-- are the 1,200 addresses each matched with itself, which is to say the view
-- is 95% noise and the noise is indistinguishable from the signal in any
-- summary built on it.
--
-- The count of "shared addresses" on the fraud dashboard has therefore tracked
-- the size of the address table rather than anything about fraud, and it goes
-- up every month, which reads as a worsening problem.
CREATE VIEW legacy.v_shared_postcodes AS
SELECT a.id            AS address_id,
       a.customer_id   AS customer_id,
       b.customer_id   AS other_customer_id,
       a.postcode,
       a.city
FROM legacy.addresses a
JOIN legacy.addresses b ON b.postcode = a.postcode;

-- DEFECT matview-without-a-unique-index-blocks-concurrent-refresh
--
-- The product revenue rollup feeds the merchandising dashboard and is
-- refreshed on a schedule. It was given an index at creation, deliberately, so
-- that the refresh could be CONCURRENTLY and the dashboard would keep serving
-- while it ran.
--
-- REFRESH MATERIALIZED VIEW CONCURRENTLY does not need an index. It needs a
-- UNIQUE index, because it diffs the old contents against the new and has to
-- identify rows to do it. This one is a plain B-tree on product_id, and
-- product_id is in fact unique here, so the index the job needs could be
-- created today without changing a single row.
--
-- Measured: the view has one index and zero unique indexes. pg_matviews
-- reports hasindexes = true, so anything checking that the view is indexed is
-- satisfied, and the refresh still fails.
--
-- The scheduled job drops its CONCURRENTLY on failure and retries plainly,
-- which works and takes an ACCESS EXCLUSIVE lock, so the dashboard returns no
-- rows for the duration of every refresh. It was reported once as a loading
-- spinner and closed as not reproducible.
CREATE MATERIALIZED VIEW analytics.mv_product_revenue AS
SELECT oi.product_id,
       count(*)                   AS line_count,
       sum(oi.line_total_cents)   AS revenue_cents
FROM storefront.order_items oi
GROUP BY oi.product_id;

CREATE INDEX ix_mv_product_revenue_product
    ON analytics.mv_product_revenue (product_id);

COMMENT ON MATERIALIZED VIEW analytics.mv_product_revenue IS
    'Revenue per product. Refreshed nightly, intended to be CONCURRENTLY.';
